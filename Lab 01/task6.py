sample_string = "Hello, World!"
slice_from_start = sample_string[:5]
print("Slice from the start:", slice_from_start)
slice_to_end = sample_string[7:]
print("Slice to the end:", slice_to_end)
slice_negative_index = sample_string[-6:-1]
print("Slice using negative indexing:", slice_negative_index)
print("\nComplete String Slicing Demonstration:")
print("Original String:", sample_string)
print("Slice [0:5]:", sample_string[0:5])
print("Slice [7:]:", sample_string[7:])
print("Slice [-6:-1]:", sample_string[-6:-1])


